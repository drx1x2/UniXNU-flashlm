def main():
    k = bytearray(open(sys.argv[1], 'rb').read())
    if len(k) != SIZE: sys.exit(f'size {len(k)} != {SIZE}')
    rd = lambda va: struct.unpack_from('<I', k, va - BASE)[0]
    if rd(REC_VA) != REC_HEAD: sys.exit('reset_halt recorder not found at 0x...73E0B00: apply reset_halt.py first')
    if rd(SITE) not in (SMC, b(SITE, STUB3)): sys.exit(f'{SITE:#x} = {rd(SITE):#010x}: neither smc nor reset_halt stub')
