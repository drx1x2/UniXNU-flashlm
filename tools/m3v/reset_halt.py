#!/usr/bin/env python3
"""M3Z9 (DIAGNOSTIC ONLY): catch kernel-side reset requests in the same round.

M3Z8 readout: still a seconds-scale reset with no M3E record => not a plain panic.
Remaining kernel reset sources (full smc/hvc census of the kernel: only 7 sites):
  CODE 0x60  _PEHaltRestartInternal entry (0x...78D244C; PEHaltRestart, halt_all_cpus,
             kdp_machine_reboot*, panic restart all funnel here)  ESR=type ELR=caller FAR=x1
  CODE 0x61  IOPlatformExpert::haltRestart   -> br PE_halt_restart  (0x...78D1614) FAR=type
  CODE 0x62  IODTPlatformExpert::haltRestart -> br PE_halt_restart  (0x...78D3AA4) FAR=type
  CODE 0x63..0x67  ArmDTPlatform::configure PSCI SYSTEM_RESET smc #1..#5 (ESR=0x84000009)
  CODE 0x68/0x69   ArmCpu::startCPU PSCI CPU_ON smc/hvc -- only with --stop-cpuon
             (ESR=0xC4000003, FAR=target MPIDR). Use it to learn whether boot even
             reaches secondary-CPU bring-up; it halts there, so drop it next round.
Recorder (43 words) at 0x...73E0B00 (start.s NOP hole, after panic_halt's 0x73E0A00..A5C):
masks DAIF, writes M3E crumb, parks in wfe. v3.7 rows: ESR=x0, ELR=x30, FAR=x1, CODE.
Usage: reset_halt.py [--stop-cpuon] IN OUT   (apply after panic_halt.py)
"""
import struct, sys
BASE, SIZE, NOP = 0xFFFFFFF007004000, 14_917_208, 0xD503201F
VA = 0xFFFFFFF0073E0B00
REC_WORDS = 23
SITES = [  # (va, pristine insn, stub index)  stub i -> CODE 0x60+i
    (0xFFFFFFF0078D244C, 0xD10143FF, 0),   # sub sp, sp, #0x50
    (0xFFFFFFF0078D1614, 0xF0001068, 1),   # adrp x8, PE_halt_restart page
    (0xFFFFFFF0078D3AA4, 0xB0001068, 2),
    (0xFFFFFFF00795D96C, 0xD4000003, 3),   # smc #0 (SYSTEM_RESET)
    (0xFFFFFFF00795D9F0, 0xD4000003, 4),
    (0xFFFFFFF00795DBD4, 0xD4000003, 5),
    (0xFFFFFFF00795DC40, 0xD4000003, 6),
    (0xFFFFFFF00795DC60, 0xD4000003, 7),
]
CPUON = [(0xFFFFFFF00795FDC4, 0xD4000003, 8), (0xFFFFFFF00795FDCC, 0xD4000002, 9)]
REC = bytes([0xdf, 0x4f, 0x03, 0xd5, 0x03, 0x00, 0x89, 0xd2, 0x23, 0xfe, 0xa0, 0xf2, 0x03, 0xfe, 0xdf, 0xf2, 0xe3, 0xff, 0xff, 0xf2, 0x60, 0x04, 0x00, 0xf9, 0x7e, 0x08, 0x00, 0xf9, 0x61, 0x0c, 0x00, 0xf9, 0x64, 0x10, 0x00, 0xf9, 0x7e, 0x14, 0x00, 0xf9, 0xe5, 0x03, 0x00, 0x91, 0x65, 0x18, 0x00, 0xf9, 0x48, 0xa6, 0x89, 0xd2, 0x48, 0x6a, 0xa8, 0xf2, 0x08, 0xab, 0xc8, 0xf2, 0x68, 0xa6, 0xe9, 0xf2, 0x68, 0x20, 0x00, 0xf9, 0x9f, 0x3f, 0x03, 0xd5, 0x08, 0x05, 0x00, 0xd1, 0x68, 0x00, 0x00, 0xf9, 0x9f, 0x3f, 0x03, 0xd5, 0x5f, 0x20, 0x03, 0xd5, 0xff, 0xff, 0xff, 0x17, 0x04, 0x0c, 0x80, 0xd2, 0xe8, 0xff, 0xff, 0x17, 0x24, 0x0c, 0x80, 0xd2, 0xe6, 0xff, 0xff, 0x17, 0x44, 0x0c, 0x80, 0xd2, 0xe4, 0xff, 0xff, 0x17, 0x64, 0x0c, 0x80, 0xd2, 0xe2, 0xff, 0xff, 0x17, 0x84, 0x0c, 0x80, 0xd2, 0xe0, 0xff, 0xff, 0x17, 0xa4, 0x0c, 0x80, 0xd2, 0xde, 0xff, 0xff, 0x17, 0xc4, 0x0c, 0x80, 0xd2, 0xdc, 0xff, 0xff, 0x17, 0xe4, 0x0c, 0x80, 0xd2, 0xda, 0xff, 0xff, 0x17, 0x04, 0x0d, 0x80, 0xd2, 0xd8, 0xff, 0xff, 0x17, 0x24, 0x0d, 0x80, 0xd2, 0xd6, 0xff, 0xff, 0x17])

def main():
    args = [a for a in sys.argv[1:] if a != '--stop-cpuon']
    sites = SITES + (CPUON if '--stop-cpuon' in sys.argv else [])
    k = bytearray(open(args[0], 'rb').read())
    if len(k) != SIZE: sys.exit(f'size {len(k)} != {SIZE}')
    rd = lambda va: struct.unpack_from('<I', k, va - BASE)[0]
    for va, ins, _ in sites:
        if rd(va) != ins: sys.exit(f'{va:#x} = {rd(va):#010x}, expected {ins:#010x}')
    for va in range(VA - 4, VA + len(REC) + 4, 4):
        if rd(va) != NOP: sys.exit(f'{va:#x} not NOP (hole in use)')
    k[VA - BASE:VA - BASE + len(REC)] = REC
    for va, _, i in sites:
        tgt = VA + (REC_WORDS + 2 * i) * 4
        struct.pack_into('<I', k, va - BASE, 0x14000000 | (((tgt - va) >> 2) & 0x3FFFFFF))
    open(args[1], 'wb').write(k)
    print(f'reset_halt: {len(sites)} sites -> {VA:#x} ({len(REC) // 4} words), CODE 0x60..{0x60 + max(s[2] for s in sites):#x}')

if __name__ == '__main__':
    main()
